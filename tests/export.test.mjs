import test from "node:test";
import assert from "node:assert/strict";
import { generateCandidate } from "../prototype/src/generator.js";
import {
  GENERATED_SHADER_NOTICE,
  encounterRecord,
  exportFiles,
  isf,
  selfContainedHTML,
  shaderToy,
  threeJS,
} from "../prototype/src/export.js";

const candidate = generateCandidate([101,202,303,404]);

test("encounter record is reconstructable without conferring property", () => {
  const record = encounterRecord(candidate);
  assert.equal(record.schema, "tsdne-encounter-v2");
  assert.equal(record.id, candidate.id);
  assert.deepEqual(record.program, candidate.graph);
  assert.deepEqual(record.graph, candidate.graph);
  assert.equal(record.licensing.application, "GPL-3.0-or-later");
  assert.equal(record.licensing.ownershipConferred, false);
  assert.equal(record.licensing.exclusivityConferred, false);
  assert.match(record.notice, /waivable rights/i);
  assert.match(record.notice, /does not .*assert that copyright necessarily attaches/i);
});

test("generated-output notice distinguishes output waiver from generator licence", () => {
  assert.match(GENERATED_SHADER_NOTICE, /CC0 1\.0/);
  assert.match(GENERATED_SHADER_NOTICE, /GPL-3\.0-or-later/);
  assert.match(GENERATED_SHADER_NOTICE, /third-party rights/i);
});

test("all promised export formats are generated", () => {
  const files = exportFiles(candidate);
  const names = Object.keys(files);
  assert.equal(names.length, 6);
  assert.ok(names.some((name) => name.endsWith(".html")));
  assert.ok(names.some((name) => name.includes("three")));
});

test("standalone export declares WebGL2 and preserves source", () => {
  const html = selfContainedHTML(candidate);
  assert.match(html, /WebGL2 required/);
  assert.match(html, /Generated by This Shader Does Not Exist/);
  assert.match(html, new RegExp(candidate.id));
});

test("Three.js adapter declares the GLSL 3 contract", () => {
  const module = threeJS(candidate);
  assert.match(module, /RawShaderMaterial/);
  assert.match(module, /glslVersion: THREE\.GLSL3/);
  assert.match(module, /u_resolution/);
});

test("ShaderToy and ISF adapters expose target entry points", () => {
  assert.match(shaderToy(candidate), /mainImage/);
  assert.match(shaderToy(candidate), /iResolution/);
  assert.match(isf(candidate), /RENDERSIZE/);
  assert.match(isf(candidate), /gl_FragColor/);
});
